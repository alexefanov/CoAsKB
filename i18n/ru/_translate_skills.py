for skill_dir in sorted(EN.iterdir()):
    if not skill_dir.is_dir():
        continue
    name = skill_dir.name
    en_file = skill_dir / "SKILL.md"
    ru_file = RU / name / "SKILL.md"
    
    if not en_file.exists():
        continue
    
    text = en_file.read_text(encoding="utf-8")
    
    # Extract frontmatter
    parts = text.split("---", 2)
    if len(parts) < 3:
        print(f"  SKIP {name}: no frontmatter")
        continue
    
    frontmatter_text = parts[1]
    
    # Get Russian body
    ru_body = BODIES.get(name)
    if not ru_body:
        print(f"  SKIP {name}: no translation")
        continue
    
    # Rebuild: frontmatter + body
    # Add lang: ru to frontmatter if not present
    if "lang:" not in frontmatter_text:
        frontmatter_text += "\nlang: ru"
    
    result = f"---{frontmatter_text}---\n{ru_body}"
    
    ru_file.write_text(result, encoding="utf-8")
    print(f"  OK  {name}")

print("\nDone! Translated all SKILL.md files.")
